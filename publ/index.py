@app.get("/")
def index():
    return render_template("index.html")


@app.post("/command")
def command():
    choice = request.form.get("choice", "").strip()

    if choice == "0":
        return render_template("index.html", message="Сеанс связи с Госкомблагом СССР завершен. До свидания, товарищ!")

    item = MENU_ITEMS.get(choice)
    if item is None:
        return render_template("index.html", error="Неизвестная команда. Введите цифру от 0 до 5.")

    text = item["text"].format(ticket=f"ЭВМ-{randint(10000, 99999)}")
    return render_template("index.html", result_title=item["title"], result=text)


if __name__ == "__main__":
    app.run(debug=True)
