@app.get("/")
async def index():
    return send_from_directory(ROOT, "index.html")


@app.post("/api/key")
async def key():
    payload = request.get_json(silent=True) or {}
    pressed = str(payload.get("key", ""))
    output = RESPONSES.get(
        pressed.lower(),
        f"СИГНАЛ «{pressed or 'НЕИЗВЕСТНЫЙ'}» ПРИНЯТ.\n\nКОД НЕ ПРЕДУСМОТРЕН ДЛЯ ДАННОГО ТЕРМИНАЛА.",
    )
    if pressed == "2":
        output = output.format(ticket=f"ЭВМ-{random.randint(10000, 99999)}")
    return jsonify(output=output)


if __name__ == "__main__":
    app.run(host="127.0.0.1", port=8000, debug=False)
